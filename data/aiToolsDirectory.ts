// Helper Functions
export function getAllAiTools(): AiToolItem[] {
  return AI_TOOLS_DIRECTORY;
}

export function getAiToolBySlug(slug: string): AiToolItem | undefined {
  return AI_TOOLS_DIRECTORY.find((t) => t.slug === slug || t.id === slug);
}

export function getAiToolsByCategory(category: AiCategory): AiToolItem[] {
  return AI_TOOLS_DIRECTORY.filter((t) => t.category === category);
}

export function getFeaturedAiTools(): AiToolItem[] {
  return AI_TOOLS_DIRECTORY.filter((t) => t.featured);
}

export function getAlternativesForTool(slug: string): AiToolItem[] {
  const tool = getAiToolBySlug(slug);
  if (!tool) return [];

  // Match explicitly listed alternatives, or fallback to same category
  const explicit = tool.alternatives
    .map((altSlug) => getAiToolBySlug(altSlug))
    .filter((t): t is AiToolItem => Boolean(t));

  if (explicit.length >= 3) return explicit;

  const sameCat = AI_TOOLS_DIRECTORY.filter(
    (t) => t.category === tool.category && t.slug !== tool.slug && !explicit.some((e) => e.slug === t.slug)
  );

  return [...explicit, ...sameCat].slice(0, 6);
}

export function searchAiTools(query: string, category?: AiCategory): AiToolItem[] {
  const q = query.toLowerCase().trim();
  return AI_TOOLS_DIRECTORY.filter((tool) => {
    const matchesCat = !category || tool.category === category;
    if (!matchesCat) return false;
    if (!q) return true;
    return (
      tool.name.toLowerCase().includes(q) ||
      tool.tagline.toLowerCase().includes(q) ||
      tool.description.toLowerCase().includes(q) ||
      tool.tags.some((tag) => tag.toLowerCase().includes(q))
    );
  });
}
